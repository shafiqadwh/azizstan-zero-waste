## 1. เริ่มใช้งาน
1. เข้าสู่ระบบด้วยชื่อผู้ใช้ที่ได้รับ ครั้งแรกต้องตั้งรหัสผ่านใหม่
2. **ติดตั้งแอปลงหน้าจอโฮม** (ปุ่ม "ติดตั้งแอป" บนหน้างานของฉัน หรือเมนู "เพิ่มไปยังหน้าจอโฮม" ใน Safari)
3. กด **เปิดการแจ้งเตือน** เพื่อรับแจ้งเมื่อเปิดรอบ ใกล้ปิดรับคะแนน และเมื่อผลถูกส่งกลับให้แก้

## 2. หน้า "งานของฉัน"
- แท็บ **ต้องทำ · รออนุมัติ · เสร็จ** แสดงห้องและพื้นที่ที่คุณได้รับมอบหมายในรอบปัจจุบัน
- ค้นหาด้วยเลขห้อง หรือ **สแกน QR ที่ประตูห้อง** ด้วยกล้องมือถือ ระบบจะเปิดแบบฟอร์มของห้องนั้นให้
- แถบด้านบนบอกเวลาที่เหลือก่อนปิดรับคะแนน

## 3. ใส่คะแนน
1. ตรวจหัวแบบฟอร์มว่า **เลขห้อง · ชื่อห้อง · รอบ** ถูกต้อง
2. เลือกคะแนน (ไม่ให้คะแนนต้องเลือก 0 เอง ช่องว่างไม่เท่ากับ 0)
3. ถ่ายรูปสถานที่ตามจำนวนที่กำหนด **ถ่ายเฉพาะพื้นที่** หลีกเลี่ยงใบหน้านักเรียน เลือกรูปจากคลังรูปได้
4. ห้องเรียนต้องถ่ายรูป **ใบลงชื่อนักเรียน** 1 รูป ยังไม่มีใบ? กด "พิมพ์ใบลงชื่อ (PDF)" ในแบบฟอร์ม
5. ใส่คำแนะนำ (ไม่เกินจำนวนตัวอักษรที่กำหนด) แล้วกดปุ่มบันทึกด้านล่าง
- ข้อความแดงใต้การ์ดบอกว่ายังขาดอะไร เช่น "ต้องถ่ายรูปอีก 1 รูป"

### ภาคเรียนที่ให้คะแนนรายคน
- การ์ดคะแนนจะแสดง **รหัสนักเรียน** ของห้อง (ไม่แสดงชื่อ) ให้เลือกคะแนนทีละคน
- ใช้ **"ใส่ให้คนที่ยังว่าง"** เพื่อใส่คะแนนเดียวกันให้ทุกคนที่ยังไม่ได้ใส่ แล้วค่อยแก้เฉพาะบางคน
- ห้องใช้ **ค่าเฉลี่ย** ในการจัดอันดับ ถ้าห้องยังไม่มีรายชื่อในรอบนี้ ให้แจ้งผู้ดูแลระบบ

## 4. สัญญาณอ่อนหรือไม่มีเน็ต
- ต้องเปิดแบบฟอร์มตอนมีสัญญาณ หลังจากนั้นสัญญาณหลุดได้ ข้อมูลไม่หาย
- ระบบเก็บ **ร่างไว้ในเครื่อง** อัตโนมัติ (เก็บ 7 วัน) เปิดห้องเดิมอีกครั้งจะกู้คืนให้ หรือกด "ล้างร่าง"
- รูปที่ถ่ายตอนไม่มีสัญญาณจะขึ้น **"รอสัญญาณ"** และอัปโหลดเองเมื่อสัญญาณกลับมา
- กดบันทึกตอนออฟไลน์ได้ ปุ่มจะเป็น **"จะส่งเมื่อมีสัญญาณ"** และส่งให้เองเมื่อรูปขึ้นครบ (แก้ข้อมูลใด ๆ = ยกเลิกการส่งอัตโนมัติ)

## 5. หลังบันทึก
- ถ้าโรงเรียน **เปิดอนุมัติอัตโนมัติ**: ผลอนุมัติและออก PDF ทันที ("บันทึกแล้ว อนุมัติอัตโนมัติ")
- ถ้าไม่เปิด: ผลอยู่ในแท็บ **รออนุมัติ** จนผู้ดูแลอนุมัติ หรือ **ส่งกลับให้แก้** พร้อมเหตุผล
- **แก้ไขเองได้** ภายในเวลาที่แสดงบนหน้ารายละเอียด ("แก้ไขเองได้อีก …") ทุกครั้งที่แก้ผลที่อนุมัติแล้ว ระบบออก PDF ฉบับใหม่
- เลยเวลาแล้ว กด **ขออนุมัติแก้ไข** เลือกชนิด (แก้คะแนน · แก้รูป · แก้ข้อติชม · ย้ายไปห้องที่ถูกต้อง · ลบผลประเมิน) พร้อมเหตุผลอย่างน้อย 5 ตัวอักษร
- ลืมใส่จนปิดรับคะแนน กด **ขออนุมัติใส่คะแนน** ในแบบฟอร์ม
- ติดตามคำขอทั้งหมดได้ที่แท็บ **คำขอของฉัน**

## 6. ครูผู้รับผิดชอบพื้นที่: หักคะแนน
ใช้เฉพาะภาคเรียนที่ผู้ดูแลเปิดส่วน "หักคะแนน"
