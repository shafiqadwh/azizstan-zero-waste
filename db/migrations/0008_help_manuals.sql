## 2. อนุมัติอัตโนมัติ
- สวิตช์อยู่ที่ **ตั้งค่า › รูปแบบการประเมิน** และด้านบนหน้า **รออนุมัติ** เปลี่ยนได้ทุกเมื่อ
- เปิด: ผลที่กรรมการบันทึกจะอนุมัติและออก PDF ทันที (ผู้อนุมัติใน PDF = "อนุมัติอัตโนมัติ") กรรมการแก้เองได้ภายในเวลาที่กำหนด
- คำขอทุกชนิดยังต้องให้แอดมินพิจารณาเสมอ
- มีผลกับผลที่บันทึกหลังเปิดเท่านั้น ผลที่รออยู่ก่อนหน้ายังต้องอนุมัติตามปกติ

## 3. ระหว่างรอบ
- **ภาพรวม**: ห้อง/อาคารที่มีคะแนนแล้ว รออนุมัติ เลยกำหนด และปุ่ม **แจ้งเตือนกรรมการที่ค้าง**
- **รออนุมัติ › ผลประเมิน**: ดูรูปและคะแนน แล้ว **อนุมัติและออก PDF** หรือ **ส่งกลับ** พร้อมเหตุผล (คีย์ลัด J/K เลื่อน, A อนุมัติ, R ส่งกลับ)
- **รออนุมัติ › คำขอ**: เห็นค่าเดิม → ค่าใหม่ อนุมัติหรือปฏิเสธ คำขอใส่คะแนนย้อนหลังกำหนดจำนวนชั่วโมงได้
- **ติดตามสถานะ** (monitor): แผนผังทุกห้อง/พื้นที่ ตัวกรอง ส่งออก Excel และสั่งสร้าง PDF ใหม่เมื่อสร้างไม่สำเร็จ

## 4. ปิดรอบ
- กด **ปิดรอบ** ได้เมื่อรอบปิดรับคะแนนแล้ว ทุกห้องและทุกอาคารมีคะแนนอนุมัติครบ และไม่มีคำขอค้าง
- ปิดรอบแล้วคะแนนและอันดับถูกตรึง PDF ไม่มีลายน้ำ "ฉบับร่าง" ผู้ดูแลระบบสูงสุดเท่านั้นที่แก้ผลหลังปิดรอบได้ (ผ่านคำขอ)

## 5. เอกสารที่พิมพ์ได้
- **ใบลงชื่อนักเรียน** ของแต่ละห้อง/รอบ (ลิงก์ในแบบฟอร์มและหน้าติดตาม)
- **QR ประตูห้อง** ที่ ตั้งค่า › ห้องเรียน: "พิมพ์ QR ทุกห้อง" หรือรายอาคาร (ตั้ง APP_URL ของเซิร์ฟเวอร์ให้ถูกก่อนพิมพ์)
- **PDF รวมทั้งรอบ** จากภาพรวมหรือหน้าตั้งค่ารอบ (เฉพาะผลที่อนุมัติแล้ว)
- **ปฏิทินการประเมิน** หน้า /calendar และไฟล์ .ics สำหรับปฏิทินมือถือ

## 6. ปิดภาคเรียนและข้อมูลส่วนบุคคล
