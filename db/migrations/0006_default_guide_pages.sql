## ภาพรวม
ในแต่ละภาคเรียนมีการประเมินหลายรอบ แต่ละรอบคณะกรรมการจะประเมิน

- **ห้องเรียน** ของแต่ละห้อง
- **อาคารหรือโซน** ที่ห้องเรียนนั้นรับผิดชอบ

คะแนนของห้องในรอบนั้น = คะแนนห้องเรียน + คะแนนอาคาร/โซนที่ห้องรับผิดชอบ
